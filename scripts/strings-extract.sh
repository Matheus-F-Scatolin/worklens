#!/usr/bin/env bash
# Every interface string the code asks the bundle for, read straight out of the source (#161).
#
# `genstrings` and `xcstringstool` are both absent under the Command Line Tools, so this is a
# regex over `Sources/`, and the call shapes it knows are the only ones allowed to carry a key:
#
#   String(localized: "…")        the Worklens target's SwiftUI strings
#   L10n.string("…")              WorklensCore, which cannot import SwiftUI
#   L10n.format("…", …)           the same, with %@/%lld holes
#   L10n.plural(count:one:other:) a counted noun — `other` is the stringsdict key
#
# Three SwiftUI shapes take a bare literal as a `LocalizedStringKey`, which *is* a live lookup at
# render time — so a literal left in one of them is translated behind this script's back, and only
# by accident, when some other pane happens to have added the same key. They are read here too,
# which makes `make lint-strings` fail on the bare form and pushes it to `String(localized:)` (the
# `StringProtocol` overload, so the lookup still happens exactly once):
#
#   TableColumn("…")              a Table header
#   DatePicker("…", …)            a date field's label
#   .alert("…", …)                an alert's title
#
# A key must be one literal on one line. Splitting a sentence with `+` hides it from this script
# and therefore from every translator; `make lint-strings` is what catches that.
#
# Modes:
#   (none)      the singular keys, sorted, one per line
#   --plurals   the plural keys (the `other` literal), sorted
#   --strings   a Localizable.strings body for the singular keys, English on both sides
#   --missing   the keys that are in the code but not in Resources/en.lproj
set -euo pipefail

cd "$(dirname "$0")/.."

SOURCES=Sources
EN_STRINGS=Resources/en.lproj/Localizable.strings
EN_DICT=Resources/en.lproj/Localizable.stringsdict

# A Swift literal is not a key until its escapes are resolved: `\u{2026}` is one character to the
# compiler and to `Bundle.localizedString`, and three to a `.strings` file, which has no `\u{…}`
# form at all. Everything downstream — the catalog, the diff, the lint — works on the resolved
# string, and `--strings` escapes it again on the way out, the way a property list wants.
unescape() {
  python3 -c '
import re, sys
CODES = {"n": "\n", "t": "\t", "r": "\r", "0": "\0"}
def one(m):
    body = m.group(1)
    if body.startswith("u{"):
        return chr(int(body[2:-1], 16))
    return CODES.get(body, body)
for line in sys.stdin:
    sys.stdout.write(re.sub(r"\\(u\{[0-9A-Fa-f]+\}|.)", one, line.rstrip("\n")) + "\n")
'
}

# One perl pass per file, slurped, because a `L10n.plural(...)` call is usually four lines.
singular_keys() {
  find "$SOURCES" -name '*.swift' -print0 \
    | xargs -0 perl -0777 -ne '
        while (/String\(\s*localized:\s*"((?:[^"\\]|\\.)*)"/gs) { print "$1\n" }
        while (/L10n\.(?:string|format)\(\s*"((?:[^"\\]|\\.)*)"/gs) { print "$1\n" }
        while (/(?:TableColumn|DatePicker)\(\s*"((?:[^"\\]|\\.)*)"/gs) { print "$1\n" }
        while (/\.alert\(\s*"((?:[^"\\]|\\.)*)"/gs) { print "$1\n" }
      ' \
    | unescape \
    | LC_ALL=C sort -u
}

plural_keys() {
  find "$SOURCES" -name '*.swift' -print0 \
    | xargs -0 perl -0777 -ne '
        while (/L10n\.plural\(\s*count:.*?other:\s*"((?:[^"\\]|\\.)*)"/gs) { print "$1\n" }
      ' \
    | unescape \
    | LC_ALL=C sort -u
}

# The keys a catalog file declares. `plutil -convert json` rather than a grep: a .strings file is
# a property list, and its own parser is the only thing that agrees with CFBundle at runtime.
catalog_keys() {
  plutil -convert json -o - "$1" \
    | python3 -c 'import json,sys; [print(k) for k in json.load(sys.stdin)]' \
    | LC_ALL=C sort -u
}

case "${1:-}" in
  --plurals) plural_keys ;;
  --strings)
    echo '/* Generated by scripts/strings-extract.sh — the English is the key. */'
    singular_keys | python3 -c '
import sys
for line in sys.stdin:
    key = line.rstrip("\n").replace("\\", "\\\\").replace("\"", "\\\"")
    print("\"%s\" = \"%s\";" % (key, key))
'
    ;;
  --missing)
    { singular_keys; catalog_keys "$EN_STRINGS"; } | LC_ALL=C sort | uniq -u \
      | LC_ALL=C comm -12 - <(singular_keys)
    { plural_keys; catalog_keys "$EN_DICT"; } | LC_ALL=C sort | uniq -u \
      | LC_ALL=C comm -12 - <(plural_keys)
    ;;
  "") singular_keys ;;
  *) echo "usage: $0 [--plurals|--strings|--missing]" >&2; exit 2 ;;
esac
